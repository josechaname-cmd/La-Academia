import assert from 'node:assert/strict';
import {evaluationState,remainingLabel} from '../public/frontend/components/evaluation-state.js';
const questions=Array.from({length:10},(_,i)=>({prompt:`Pregunta ${i}`,choices:['A','B','C']}));
let now=10000;
const state=evaluationState({token:'private-attempt',questions,server_time:1000,expires_at:1060},()=>now);
assert.equal(state.completed(),0);assert.equal(state.missing(),0);assert.equal(state.remaining(),60);
assert.throws(()=>state.payload(),/Responde todas/);
state.choose(0,0);assert.equal(state.completed(),1);assert.equal(state.missing(),1);
state.choose(0,2);assert.equal(state.completed(),1,'Changing answer does not increase progress');
assert.throws(()=>state.choose(10,0));assert.throws(()=>state.choose(0,3));assert.throws(()=>state.choose(0,null));
for(let i=1;i<10;i++)state.choose(i,i%3);
assert.equal(state.missing(),-1);assert.equal(state.completed(),10);
const payload=state.payload();assert.equal(payload.token,'private-attempt');assert.equal(payload.answers[0],2);
payload.answers[0]=1;assert.equal(state.answers[0],2,'Submission is an independent snapshot');
now+=30000;assert.equal(state.remaining(),30);
now+=40000;assert.equal(state.remaining(),0,'Time expires while the dialog is closed');
assert.equal(remainingLabel(30),'00:30');assert.equal(remainingLabel(125),'02:05');assert.equal(remainingLabel(0),'00:00');
assert.equal(evaluationState({questions,expires_at:null}).remaining(),null);
console.log('OK evaluación: respuestas, edición, progreso, pendientes, envío completo, copia y plazo del servidor.');
