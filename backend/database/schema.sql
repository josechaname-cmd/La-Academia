CREATE TABLE IF NOT EXISTS sites (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE,
 address VARCHAR(250) NOT NULL DEFAULT '', active TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS admins (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, dni CHAR(8) NULL,
 job_title VARCHAR(160) NOT NULL DEFAULT '',
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS auth_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ip_hash CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, INDEX idx_auth_ip (ip_hash,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, scope ENUM('course','event') NOT NULL,
 name VARCHAR(80) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_category_scope_name (scope,name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS courses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, site_id BIGINT UNSIGNED NULL,
 created_by BIGINT UNSIGNED NULL, creator_name VARCHAR(120) NOT NULL DEFAULT '', title VARCHAR(160) NOT NULL,
 category VARCHAR(40) NOT NULL, description TEXT NOT NULL, duration INT UNSIGNED NULL DEFAULT NULL,
 view_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
 exam_required TINYINT(1) NOT NULL DEFAULT 1,
 first_published_at DATETIME NULL,
 status ENUM('draft','published','archived') NOT NULL DEFAULT 'draft',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_course_status (status,category)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS files (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, course_id BIGINT UNSIGNED NULL,
 original_name VARCHAR(220) NOT NULL, storage_key VARCHAR(90) NOT NULL UNIQUE,
 mime VARCHAR(100) NOT NULL, extension VARCHAR(8) NOT NULL, size BIGINT UNSIGNED NOT NULL,
 duration_seconds DECIMAL(12,3) NULL, video_width INT UNSIGNED NULL, video_height INT UNSIGNED NULL,
 video_codec VARCHAR(24) NULL, audio_codec VARCHAR(24) NULL,
 slides_json LONGTEXT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS announcements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, kind ENUM('banner','notification') NOT NULL,
 title VARCHAR(160) NOT NULL, body TEXT NOT NULL, image_id BIGINT UNSIGNED NULL,
 course_id BIGINT UNSIGNED NULL, active TINYINT(1) NOT NULL DEFAULT 1,
 position INT NOT NULL DEFAULT 0, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (image_id) REFERENCES files(id) ON DELETE SET NULL,
 FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE SET NULL,
 INDEX idx_announcements (kind,active,position)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(160) NOT NULL,
 description TEXT NOT NULL, category VARCHAR(80) NOT NULL DEFAULT '', location VARCHAR(160) NOT NULL,
 view_count BIGINT UNSIGNED NOT NULL DEFAULT 0,
 starts_at DATETIME NOT NULL, image_id BIGINT UNSIGNED NULL, active TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (image_id) REFERENCES files(id) ON DELETE SET NULL,
 INDEX idx_events (active,category,starts_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS event_images (
 event_id BIGINT UNSIGNED NOT NULL, file_id BIGINT UNSIGNED NOT NULL, position INT UNSIGNED NOT NULL,
 PRIMARY KEY(event_id,position), UNIQUE KEY uq_event_file(event_id,file_id),
 FOREIGN KEY(event_id) REFERENCES events(id) ON DELETE CASCADE,
 FOREIGN KEY(file_id) REFERENCES files(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS exams (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, course_id BIGINT UNSIGNED NOT NULL,
 version INT UNSIGNED NOT NULL, questions_json LONGTEXT NOT NULL,
 opens_at DATETIME NULL, closes_at DATETIME NULL, duration_minutes INT UNSIGNED NULL, enabled TINYINT(1) NOT NULL DEFAULT 1,
 max_attempts TINYINT UNSIGNED NOT NULL DEFAULT 2, passing_score TINYINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_exam_version (course_id,version),
 FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS employees (
 dni CHAR(8) PRIMARY KEY, full_name VARCHAR(120) NOT NULL, job_title VARCHAR(160) NOT NULL, site_id BIGINT UNSIGNED NULL,
 active TINYINT(1) NOT NULL DEFAULT 1, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_employee_active (active,full_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS enrollments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, exam_id BIGINT UNSIGNED NOT NULL,
 dni CHAR(8) NOT NULL, name VARCHAR(120) NOT NULL, job_title VARCHAR(160) NOT NULL DEFAULT '',
 phone CHAR(9) NOT NULL, area VARCHAR(80) NOT NULL,
 UNIQUE KEY uq_exam_dni (exam_id,dni),
 FOREIGN KEY (exam_id) REFERENCES exams(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, enrollment_id BIGINT UNSIGNED NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE, status ENUM('pending','completed') NOT NULL DEFAULT 'pending',
 score INT NULL, answers_json TEXT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 submitted_at DATETIME NULL, INDEX idx_enrollment_status (enrollment_id,status),
 FOREIGN KEY (enrollment_id) REFERENCES enrollments(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS activity_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 event_key VARCHAR(190) NOT NULL UNIQUE, event_type VARCHAR(60) NOT NULL,
 entity_type VARCHAR(30) NOT NULL, entity_id BIGINT UNSIGNED NOT NULL,
 course_id BIGINT UNSIGNED NULL, exam_id BIGINT UNSIGNED NULL,
 title VARCHAR(180) NOT NULL, body VARCHAR(500) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 recorded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_activity_entity (entity_type,entity_id), INDEX idx_activity_exam (exam_id),
 INDEX idx_activity_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS home_popup (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(160) NOT NULL DEFAULT '',
 image_id BIGINT UNSIGNED NULL,
 link_url VARCHAR(1000) NOT NULL DEFAULT '',
 link_label VARCHAR(80) NOT NULL DEFAULT '',
 active TINYINT(1) NOT NULL DEFAULT 0,
 revision BIGINT UNSIGNED NOT NULL DEFAULT 0,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (image_id) REFERENCES files(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
