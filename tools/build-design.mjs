// Build explicit scoped CSS; runtime has no build/dependency requirement.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(path.join(root,'tests/package.json'));
const postcss=require('postcss');
const source=path.join(root,'public/frontend/design');
const tokens=JSON.parse(fs.readFileSync(path.join(source,'tokens.json'),'utf8'));
const checking=process.argv.includes('--check');
function write(file,text){
  text=text.trimEnd()+'\n';
  const target=path.join(root,file);
  if(checking){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==text)throw Error(`Diseño desactualizado: ${file}. Ejecuta node tools/build-design.mjs`);}
  else if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==text)fs.writeFileSync(target,text);
}
function compile(filename){
  const css=postcss.parse(fs.readFileSync(path.join(source,filename),'utf8'),{from:filename});
  css.walkAtRules('media',rule=>{
    rule.params=rule.params.replace(/--screen-([a-z]+)/g,(_,name)=>{
      if(!tokens.breakpoints[name])throw Error(`Breakpoint desconocido: ${name}`);
      return `max-width: ${tokens.breakpoints[name]}px`;
    });
  });
  css.walkRules(rule=>{
    if(rule.parent.type==='atrule'&&/keyframes$/.test(rule.parent.name))return;
    rule.selectors=rule.selectors.map(selector=>{
      if(!selector.trim())throw Error(`Empty selector in ${filename}`);
      if(selector.startsWith('.academy-ui')||selector.startsWith(':where(.academy-ui)'))return selector;
      if(selector===':root'||selector==='html')return '.academy-ui';
      if(selector.startsWith('html:'))return '.academy-ui'+selector.slice(4);
      return `:where(.academy-ui) ${selector}`;
    });
  });
  return css.toString();
}
const header='/* Generated by tools/build-design.mjs. Edit public/frontend/design/, not this file. */\n';
const declarations=Object.entries(tokens).filter(([group])=>group!=='breakpoints').flatMap(([group,values])=>Object.entries(values).map(([name,value])=>`  --ds-${group}-${name}: ${value};`)).join('\n');
const aliases={blue:'color-brand',navy:'color-ink',teal:'color-teal',muted:'color-muted',line:'color-line',paper:'color-canvas',mint:'color-success-bg',lime:'color-accent',font:'font-family'};
const aliasCss=Object.entries(aliases).map(([key,value])=>`  --${key}: var(--ds-${value});`).join('\n');
write('public/assets/design-system.css',header+`.academy-ui {\n${declarations}\n${aliasCss}\n}\n`+compile('foundation.css')+'\n'+compile('navigation.css')+'\n'+compile('components.css')+'\n'+compile('carousel.css')+'\n'+compile('home-popup.css')+'\n'+compile('public-shell.css')+'\n');
write('public/assets/styles.css',header+compile('layouts/base.css')+'\n');
write('public/assets/learning.css',header+compile('layouts/learning.css')+'\n'+compile('pages/admin-dashboard.css')+'\n');
write('public/frontend/design/runtime.js',header+`export const screens=Object.freeze(${JSON.stringify(tokens.breakpoints)});\nexport const motion=Object.freeze(${JSON.stringify({fast:parseInt(tokens.motion.fast),normal:parseInt(tokens.motion.normal),toast:Number(tokens.motion.toast),carousel:Number(tokens.motion.carousel)})});\n`);
console.log(checking?'OK diseño generado sincronizado.':'Diseño compilado: tokens, componentes, composiciones y breakpoints JS.');
